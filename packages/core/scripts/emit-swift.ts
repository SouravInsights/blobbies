/**
 * Generate the Swift data file from `manifest.json`.
 *
 * The big, hand-tuned data (36 glyphs, 22 expressions, 5 egg shapes, the
 * layout) is never retyped in Swift. It is emitted from the one source of
 * truth, so a change to a mouth or a glyph reaches Swift automatically.
 *
 * Run `pnpm --filter blobbies codegen:swift`, then commit both files.
 */
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const MANIFEST = resolve(here, '../manifest.json');
const OUT = resolve(here, '../../../platforms/swift/Sources/Blobbies/Generated.swift');

type Mouth = Record<string, unknown>;

function mouthExpr(mouth: Mouth): string {
  if (Array.isArray(mouth.half)) {
    const [rx, ry] = mouth.half as number[];
    return `.half(rx: ${rx}, ry: ${ry}, tongue: ${mouth.tongue === true})`;
  }
  if (Array.isArray(mouth.circle)) {
    const [dx, dy, r] = mouth.circle as number[];
    return `.circle(dx: ${dx}, dy: ${dy}, r: ${r})`;
  }
  if (Array.isArray(mouth.ellipse)) {
    const [dx, dy, rx, ry] = mouth.ellipse as number[];
    return `.ellipse(dx: ${dx}, dy: ${dy}, rx: ${rx}, ry: ${ry})`;
  }
  return `.stroke(d: ${JSON.stringify(mouth.d)}, width: ${mouth.width}, tongue: ${mouth.tongue === true})`;
}

function main(): void {
  const m = JSON.parse(readFileSync(MANIFEST, 'utf8'));
  const out: string[] = [];

  out.push('// Generated by packages/core/scripts/emit-swift.ts — do not edit by hand.');
  out.push('// Source: packages/core/manifest.json');
  out.push('import Foundation');
  out.push('');
  out.push('enum BlobData {');
  out.push(`  static let contract: Int = ${m.contract}`);
  out.push(`  static let viewBox = ${JSON.stringify(m.viewBox)}`);
  out.push(`  static let backdrop = ${JSON.stringify(m.colors.backdrop)}`);
  out.push(`  static let ink = ${JSON.stringify(m.colors.ink)}`);
  out.push(`  static let blush = ${JSON.stringify(m.colors.blush)}`);
  out.push(`  static let blushOpacity: Double = ${m.colors.blushOpacity}`);
  out.push(`  static let strokeWidth: Double = ${m.strokeWidth}`);
  out.push(`  static let inkWidth: Double = ${m.inkWidth}`);
  out.push(`  static let letterBoxWidth: Double = ${m.letterBox.width}`);
  out.push(`  static let letterBoxHeight: Double = ${m.letterBox.height}`);
  out.push('');
  out.push(`  static let palette: [String] = [${m.palette.map((p: { value: string }) => JSON.stringify(p.value)).join(', ')}]`);
  out.push('');
  out.push('  static let letters: [String: String] = [');
  for (const [key, value] of Object.entries(m.letters as Record<string, string>)) {
    out.push(`    ${JSON.stringify(key)}: ${JSON.stringify(value)},`);
  }
  out.push('  ]');
  out.push('');
  out.push('  static let shapes: [ShapeGeometry] = [');
  for (const shape of m.shapes as Array<{ name: string; rx: number; ry: number; eb: number }>) {
    out.push(`    ShapeGeometry(name: ${JSON.stringify(shape.name)}, rx: ${shape.rx}, ry: ${shape.ry}, eb: ${shape.eb}),`);
  }
  out.push('  ]');
  out.push('');
  out.push('  static let expressions: [Expression] = [');
  for (const e of m.expressions as Array<{
    key: string;
    name: string;
    mouth: Mouth;
    brow: string;
    eye?: [number, number];
    squint?: string;
  }>) {
    const eye = e.eye ? `EyeShift(x: ${e.eye[0]}, y: ${e.eye[1]})` : 'nil';
    const squint = e.squint ? JSON.stringify(e.squint) : 'nil';
    out.push(
      `    Expression(key: ${JSON.stringify(e.key)}, name: ${JSON.stringify(e.name)}, mouth: ${mouthExpr(e.mouth)}, brow: ${JSON.stringify(e.brow)}, eye: ${eye}, squint: ${squint}),`,
    );
  }
  out.push('  ]');
  out.push('');
  const L = m.layout;
  out.push('  static let layout = Layout(');
  out.push(`    backdrop: .init(cx: ${L.backdrop.cx}, cy: ${L.backdrop.cy}, r: ${L.backdrop.r}),`);
  out.push(`    blob: .init(cx: ${L.blob.cx}, bottom: ${L.blob.bottom}),`);
  out.push(`    eyes: .init(cx: ${L.eyes.cx}, cy: ${L.eyes.cy}, scale: ${L.eyes.scale}, visualGap: ${L.eyes.visualGap}),`);
  out.push(`    mouth: .init(cx: ${L.mouth.cx}, cy: ${L.mouth.cy}),`);
  out.push(
    `    cheeks: [${(L.cheeks as Array<{ cx: number; cy: number; rx: number; ry: number }>)
      .map((c) => `.init(cx: ${c.cx}, cy: ${c.cy}, rx: ${c.rx}, ry: ${c.ry})`)
      .join(', ')}]`,
  );
  out.push('  )');
  out.push('}');
  out.push('');

  mkdirSync(dirname(OUT), { recursive: true });
  writeFileSync(OUT, out.join('\n'), 'utf8');
  process.stdout.write(`wrote ${OUT}\n`);
}

main();
