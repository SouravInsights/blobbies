#!/usr/bin/env node
/**
 * Regenerates `src/logos.ts` from svgl (https://svgl.app).
 *
 * The marks are brand assets, so they are taken from an icon library rather
 * than drawn: a guessed path for a brand mark is a wrong logo. svgl carries the
 * real multi-colour versions, which is why it is used here rather than a
 * monochrome set.
 *
 * This script is committed so the file can be regenerated, and its output is
 * committed too, so builds are deterministic and need no network.
 *
 *   node scripts/fetch-logos.mjs
 *
 * React is the only mark that ships in two variants; the dark-background one is
 * used, because this page is dark by default.
 */
import { writeFileSync } from 'node:fs';

const SOURCES = {
  react: 'https://svgl.app/library/react_dark.svg',
  vue: 'https://svgl.app/library/vue.svg',
  svelte: 'https://svgl.app/library/svelte.svg',
  swift: 'https://svgl.app/library/swift.svg',
  javascript: 'https://svgl.app/library/javascript.svg',
  html5: 'https://svgl.app/library/html5.svg',
  docker: 'https://svgl.app/library/docker.svg',
};

/** Drop everything that does not affect drawing, and let CSS set the size. */
function clean(svg) {
  return svg
    .replace(/<\?xml[^>]*\?>/g, '')
    .replace(/<!--[\s\S]*?-->/g, '')
    .replace(/<title>[\s\S]*?<\/title>/g, '')
    .replace(/<desc>[\s\S]*?<\/desc>/g, '')
    // `stroke-width` is safe: the `-` means there is no whitespace before
    // `width`, which the pattern requires.
    .replace(/\s+(width|height)="[^"]*"/g, '')
    .replace(/>\s+</g, '><')
    .replace(/\s+/g, ' ')
    .trim();
}

const logos = {};
for (const [id, url] of Object.entries(SOURCES)) {
  const response = await fetch(url);
  if (!response.ok) throw new Error(`${id}: ${response.status} ${response.statusText}`);
  logos[id] = clean(await response.text());
}

const entries = Object.entries(logos)
  .map(([id, svg]) => `  ${id}: ${JSON.stringify(svg)},`)
  .join('\n');

writeFileSync(
  new URL('../src/logos.ts', import.meta.url),
  `/**
 * Brand marks, taken from svgl (https://svgl.app) and inlined.
 *
 * Generated by \`node scripts/fetch-logos.mjs\`. Do not edit by hand — run the
 * script instead.
 */
export const LOGOS: Record<string, string> = {
${entries}
};
`,
);

console.log(`wrote src/logos.ts — ${Object.keys(logos).length} marks`);
for (const [id, svg] of Object.entries(logos)) {
  console.log(`  ${id.padEnd(12)} ${String(svg.length).padStart(5)} B`);
}
